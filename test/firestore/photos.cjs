const { initializeTestEnvironment, assertSucceeds, assertFails } = require('@firebase/rules-unit-testing');
const { doc, setDoc, getDoc, serverTimestamp, Bytes, updateDoc } = require('firebase/firestore');
const fs = require('fs');
(async () => {
 const env = await initializeTestEnvironment({projectId: 'demo-real-estate', firestore: {host:'127.0.0.1', port:8787, rules:fs.readFileSync(require('path').join(__dirname,'../../firestore.rules'),'utf8')}});
 const owner = env.authenticatedContext('owner').firestore();
 const other = env.authenticatedContext('other').firestore();
 const consumer = env.authenticatedContext('consumer').firestore();
 const untyped = env.authenticatedContext('untyped').firestore();
 const guest = env.unauthenticatedContext().firestore();
 const photo = n => Bytes.fromUint8Array(new Uint8Array(n));
 const listing = photos => ({title:'Test',type:'Apartment',governorate:'Luxor',location:'Luxor',mode:'rent',price:100,bedrooms:2,bathrooms:1,area:90,description:'',photoBytes:photos,ownerId:'owner',status:'available',createdAt:serverTimestamp(),lastConfirmedAt:serverTimestamp()});
 try {
  const profile = role => ({name:'Test', phone:'01012345678', role, createdAt:serverTimestamp()});
  await assertSucceeds(setDoc(doc(owner,'users/owner'),profile('owner')));
  await assertSucceeds(setDoc(doc(other,'users/other'),profile('owner')));
  await assertSucceeds(setDoc(doc(consumer,'users/consumer'),profile('consumer')));
  await assertFails(setDoc(doc(untyped,'users/untyped'),profile('admin')));
  await assertFails(setDoc(doc(untyped,'users/untyped'),{...profile('owner'),phone:'123'}));
  await assertFails(setDoc(doc(untyped,'users/someone-else'),profile('owner')));
  await assertFails(updateDoc(doc(consumer,'users/consumer'),{role:'owner'}));
  await assertFails(getDoc(doc(other,'users/owner')));
  await assertSucceeds(getDoc(doc(owner,'users/owner')));
  await assertFails(setDoc(doc(consumer,'properties/consumer'),{...listing([photo(1)]),ownerId:'consumer'}));
  await assertFails(setDoc(doc(untyped,'properties/untyped'),{...listing([photo(1)]),ownerId:'untyped'}));
  await assertSucceeds(setDoc(doc(owner,'properties/valid'),listing([photo(122880),photo(122880),photo(122880),photo(122880)])));
  await assertFails(setDoc(doc(owner,'properties/too-big'),listing([photo(122881)])));
  await assertFails(setDoc(doc(owner,'properties/too-many'),listing(Array(5).fill(photo(1)))));
  await assertFails(setDoc(doc(owner,'properties/empty'),listing([])));
  await assertFails(setDoc(doc(owner,'properties/empty-photo'),listing([photo(0)])));
  await assertFails(setDoc(doc(owner,'properties/string'),listing(['not bytes'])));
  await assertFails(setDoc(doc(other,'properties/wrong-owner'),listing([photo(1)])));
  await assertFails(setDoc(doc(guest,'properties/guest'),listing([photo(1)])));
  await assertSucceeds(getDoc(doc(guest,'properties/valid')));
  await assertSucceeds(updateDoc(doc(owner,'properties/valid'),{lastConfirmedAt:serverTimestamp()}));
  await assertFails(updateDoc(doc(other,'properties/valid'),{lastConfirmedAt:serverTimestamp()}));
  await assertFails(updateDoc(doc(owner,'properties/valid'),{photoBytes:[photo(2)]}));
  const viewing = (userId) => ({customerName:'Test',customerPhone:'01012345678',propertyId:'valid',propertyTitle:'Test',location:'Luxor',governorate:'Luxor',requestedDate: new Date(Date.now()+86400000),requestedTime:'12:00',status:'pending',userId,ownerId:'owner',createdAt:serverTimestamp()});
  await assertSucceeds(setDoc(doc(consumer,'viewing_requests/valid'),viewing('consumer')));
  await assertFails(setDoc(doc(owner,'viewing_requests/owner'),viewing('owner')));
  await assertFails(setDoc(doc(untyped,'viewing_requests/untyped'),viewing('untyped')));
  await assertFails(updateDoc(doc(consumer,'properties/valid'),{lastConfirmedAt:serverTimestamp()}));
  console.log('27 Firestore rules assertions passed');
 } finally { await env.cleanup(); }
})().catch(e => {console.error(e);process.exit(1)});
